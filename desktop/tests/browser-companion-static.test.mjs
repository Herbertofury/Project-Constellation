import assert from 'node:assert/strict';
import fsp from 'node:fs/promises';

const manifest = JSON.parse(await fsp.readFile(new URL('../../extension/manifest.json', import.meta.url), 'utf8'));
const background = await fsp.readFile(new URL('../../extension/src/local-work-controller.js', import.meta.url), 'utf8');
const pageHook = await fsp.readFile(new URL('../../extension/src/local-work-page-hook.js', import.meta.url), 'utf8');
const content = await fsp.readFile(new URL('../../extension/src/local-work-content.js', import.meta.url), 'utf8');

assert.equal(manifest.manifest_version, 3);
assert.equal(manifest.version, '0.22.0');
assert.ok(typeof manifest.key === 'string' && manifest.key.length > 300);
assert.match(await fsp.readFile(new URL('../src/browser-bridge.mjs', import.meta.url), 'utf8'), /geljambmkfjkhodgkpjhnmfojkpcamig/);
assert.ok(manifest.content_scripts.length >= 2);
assert.ok(manifest.content_scripts[0].matches.includes('https://chatgpt.com/*'));
assert.equal(manifest.content_scripts[0].world, 'MAIN');
assert.equal(manifest.content_scripts[0].run_at, 'document_start');
assert.ok(manifest.content_scripts.some(row => row.world === 'MAIN' && row.js?.includes('src/local-work-page-hook.js')));
assert.ok(manifest.content_scripts.some(row => row.js?.includes('src/local-work-content.js')));
assert.ok(manifest.host_permissions.includes('http://127.0.0.1:47721/*'));
assert.ok(manifest.host_permissions.includes('http://localhost:47721/*'));
assert.ok(manifest.host_permissions.includes('https://chatgpt.com/*'));
assert.ok(manifest.host_permissions.includes('https://chat.openai.com/*'));
assert.doesNotMatch(background, /api\.openai\.com|work mode|responses api/i);
assert.match(background, /127\.0\.0\.1:47721/);
assert.match(background, /versionMismatch/);
assert.doesNotMatch(background, /setBadge/);
assert.match(background, /runtime\.onInstalled/);
assert.match(background, /pcxStoreDesktopStatus/);
assert.match(pageHook, /window\.fetch/);
assert.match(pageHook, /CC_PAGE_CONTEXT_INJECTED_V2/);
