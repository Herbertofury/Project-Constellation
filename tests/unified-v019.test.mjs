assert.equal(pkg.version,'0.24.0'); assert.equal(pkg.build.productName,'Project Constellation');
const companionDir='desktop/browser-companion';
assert.ok(fs.existsSync(companionDir));
assert.deepEqual(fs.readdirSync(companionDir).sort(),['page-hook.js']);
assert.deepEqual(fs.readFileSync(`${companionDir}/page-hook.js`),fs.readFileSync('extension/src/local-work-page-hook.js'));
for(const retired of ['manifest.json','background.js','service-worker.js','content.js','popup.html','popup.js']) assert.ok(!fs.existsSync(`${companionDir}/${retired}`));
