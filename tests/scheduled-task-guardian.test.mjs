import assert from 'node:assert/strict';
import fs from 'node:fs';

await import('../extension/src/scheduled-task-guardian-core.js');
const core=globalThis.ProjectConstellationScheduledTaskGuardianCore;
assert(core);
assert.equal(core.SCHEDULE_URL,'https://chatgpt.com/schedules');
assert.equal(core.normalizeScheduleUrl('https://chatgpt.com/scheduled?x=1'),core.SCHEDULE_URL);
assert.equal(core.normalizeScheduleUrl('https://chatgpt.com/schedules?x=1'),core.SCHEDULE_URL);
assert.equal(core.normalizeScheduleUrl('https://chatgpt.com/tasks'),core.SCHEDULE_URL);
assert.equal(core.normalizeScheduleUrl('https://evil.example/schedules'),core.SCHEDULE_URL);
assert.equal(core.normalizeScheduleUrl('javascript:alert(1)'),core.SCHEDULE_URL);
assert.equal(core.normalizeCadence(17),15);
assert.equal(core.normalizeCadence(44),30);
assert.equal(core.normalizeCadence(130),180);
const normalizedSettings=core.normalizeSettings({enabled:1,keepEmbeddedWorkspace:false,autoRepair:false,cadenceMinutes:58,observeTaskState:false,desktopNotifications:false,notifyRunCompleted:false,notifyStateChanges:false});
assert.equal(normalizedSettings.cadenceMinutes,60);
assert.equal(normalizedSettings.observeTaskState,false);
assert.equal(normalizedSettings.desktopNotifications,false);
assert.equal(normalizedSettings.notifyRunCompleted,false);
assert.equal(normalizedSettings.notifyStateChanges,false);
assert.equal(core.frameBlockReason([{name:'X-Frame-Options',value:'DENY'}]),'x-frame-options-deny');
assert.equal(core.frameBlockReason([{name:'X-Frame-Options',value:'SAMEORIGIN'}]),'x-frame-options-sameorigin');
assert.equal(core.frameBlockReason([{name:'Content-Security-Policy',value:"default-src 'self'; frame-ancestors 'self' https://chatgpt.com"}]),'csp-frame-ancestors');
assert.equal(core.frameBlockReason([{name:'Content-Security-Policy',value:'frame-ancestors *'}]),'');
assert.equal(core.authRequired({status:401,finalUrl:core.SCHEDULE_URL}),true);
assert.equal(core.authRequired({status:200,finalUrl:'https://chatgpt.com/auth/login'}),true);
assert.equal(core.deriveRuntime({settings:{enabled:false}}).status,'disabled');
assert.equal(core.deriveRuntime({settings:{enabled:true},httpStatus:200,frameReady:true}).status,'embedded');
assert.equal(core.deriveRuntime({settings:{enabled:true},httpStatus:200,frameBlocked:true}).status,'heartbeat');
assert.equal(core.deriveRuntime({settings:{enabled:true},httpStatus:200}).status,'reachable');
assert.equal(core.deriveRuntime({settings:{enabled:true},httpStatus:503}).status,'degraded');

const base={id:'task-1',title:'Morning brief',enabled:true,status:'active',lastRunId:'run-1',lastRunStatus:'completed',lastRunAt:1000};
assert.deepEqual(core.deriveTaskEvents(null,base),[],'first observation must not fabricate a transition');
assert.deepEqual(core.deriveTaskEvents(base,{...base,lastRunId:'run-2',lastRunAt:2000}).map((event)=>event.type),['run-completed']);
assert.deepEqual(core.deriveTaskEvents(base,{...base,lastRunId:'run-2',lastRunAt:2000,enabled:false,status:'paused'}).map((event)=>event.type),['run-completed-paused'],'completion + pause must collapse into one useful alert');
assert.deepEqual(core.deriveTaskEvents(base,{...base,lastRunId:'run-2',lastRunAt:2000,lastRunStatus:'failed',enabled:false,status:'paused'}).map((event)=>event.type),['run-failed-paused']);
assert.deepEqual(core.deriveTaskEvents(base,{...base,requiresAttention:true,attentionReason:'approval required'}).map((event)=>event.type),['needs-attention']);
assert.deepEqual(core.deriveTaskEvents({...base,enabled:false,status:'paused'},{...base,enabled:true,status:'active'}).map((event)=>event.type),['resumed']);
assert.equal(core.eventPresentation({type:'run-completed-paused'},{...base,enabled:false,status:'paused'}).important,true);

const background=fs.readFileSync(new URL('../extension/background.js',import.meta.url),'utf8');
const offscreen=fs.readFileSync(new URL('../extension/offscreen.js',import.meta.url),'utf8');
const pageProbe=fs.readFileSync(new URL('../extension/src/scheduled-task-page-probe.js',import.meta.url),'utf8');
const observer=fs.readFileSync(new URL('../extension/src/scheduled-task-observer.js',import.meta.url),'utf8');
const manifest=JSON.parse(fs.readFileSync(new URL('../extension/manifest.json',import.meta.url),'utf8'));
const guardianStart=background.indexOf('function defaultScheduledGuardianState()');
const guardianEnd=background.indexOf('const providerRequestLocks = new Map();',guardianStart);
const guardianSource=background.slice(guardianStart,guardianEnd);
assert(guardianSource.includes("chrome.tabs.create({ url:scheduledGuardian.SCHEDULE_URL, active:true })"),'Open Scheduled must be explicit and foreground');
assert(guardianSource.includes('chrome.notifications.create'),'Guardian task transitions must be able to create native alerts');
assert(guardianSource.includes("buttons:[{ title:'Open Scheduled' },{ title:'Mute 1 hour' }]"),'native alerts must have useful actions');
assert(background.includes("case 'PC_SCHEDULE_GUARDIAN_TASK_SNAPSHOT'"),'sanitized task snapshots must be ingested');
assert(!guardianSource.includes('active:false'),'Guardian must never create an inactive hidden tab');
assert(!guardianSource.includes('chrome.windows.create'),'Guardian must never create a minimized/hidden window');
assert(!guardianSource.includes('tabs.update'),'Guardian must not hijack or navigate an existing tab');
assert(offscreen.includes("frame.id='project-constellation-scheduled-task-guardian'"),'offscreen workspace frame exists');
assert(offscreen.includes('scheduledGuardian.normalizeScheduleUrl'),'offscreen frame URL is confined to the canonical Scheduled page');
assert(!offscreen.includes('fetch('),'offscreen frame host must not add its own polling loop');
assert(pageProbe.includes('PerformanceObserver'),'task endpoint discovery should observe resource metadata without intercepting provider fetch');
assert(!pageProbe.includes('window.fetch='),'Scheduled observer must not monkeypatch provider fetch');
assert(pageProbe.includes('BLOCKED_CHILD_KEY'),'task observation must explicitly exclude content-bearing payload fields');
assert(pageProbe.includes('session-token-missing'),'bounded refresh can reuse the signed-in ChatGPT session when needed');
assert(observer.includes('PC_SCHEDULE_GUARDIAN_REFRESH_FROM_PAGE'),'isolated bridge must support bounded page refresh requests');
assert(observer.includes('PC_SCHEDULE_GUARDIAN_TASK_SNAPSHOT'),'isolated bridge must forward sanitized task snapshots');
assert(manifest.permissions.includes('notifications'),'native Scheduled alerts require the already-existing notifications permission');
const guardianScripts=manifest.content_scripts.filter((row)=>(row.js||[]).some((file)=>file.includes('scheduled-task-')));
assert.equal(guardianScripts.length,3);
const legacyGuardianScripts=guardianScripts.filter((row)=>!(row.js||[]).includes('src/scheduled-task-recovery-page.js'));
assert.equal(legacyGuardianScripts.length,2);
assert(legacyGuardianScripts.every((row)=>row.all_frames===true),'Scheduled observer must cover the offscreen Scheduled subframe as well as visible ChatGPT pages');
const recoveryScript=guardianScripts.find((row)=>(row.js||[]).includes('src/scheduled-task-recovery-page.js'));
assert.equal(recoveryScript?.all_frames,false,'Recovery controller must stay confined to the top frame so it cannot duplicate side effects in subframes');

console.log('scheduled-task-guardian.test.mjs: PASS');
